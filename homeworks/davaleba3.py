# ინიციალიზაციას ვუკეთებთ ჯამის ცვლადს
jami = 0

# ვხსნით ახალ ფაილს ჩაწერის რეჟიმში
with open("numbers.txt", "w", encoding="utf-8") as f:
    # range(500, 1001) გადაუვლის რიცხვებს 500-დან 1000-ის ჩათვლით
    for i in range(500, 1001):
        f.write(f"{i}\n")  # თითოეულ რიცხვს წერს ახალ ხაზზე
        jami += i          # ვუმატებთ მიმდინარე რიცხვს ჯამს
    
    # ციკლის დასრულების შემდეგ, ბოლო ხაზზე ვწერთ ჯამს
    f.write(f"ჯამი: {jami}")


    